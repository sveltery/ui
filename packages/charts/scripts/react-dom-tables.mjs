// Generates src/util/reactDomTables.ts: the tables react-dom uses to turn JSX props into DOM attributes, styles and listeners.
// Usage: node scripts/react-dom-tables.mjs <path to react-dom/cjs/react-dom-client.development.js> [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [source, flag] = process.argv.slice(2);
if (!source) throw new Error('Pass the path of react-dom/cjs/react-dom-client.development.js.');
const text = readFileSync(source, 'utf8').replace(/\s+/g, ' ');
const target = join(dirname(fileURLToPath(import.meta.url)), '../src/util/reactDomTables.ts');

function match(pattern, what) {
  const found = text.match(pattern);
  if (!found) throw new Error(`Could not find ${what} in ${source}.`);
  return found;
}

const version = match(/exports\.version = "([^"]+)"/, 'the version')[1];
const setProp = match(/function setProp\(domElement, tag, key, value, props, prevValue\) \{(.*?) function setPropOnCustomElement\(/, 'setProp')[1];

// The `case "x":` labels that fall through to the body starting at `body`.
function casesBefore(body) {
  const index = setProp.indexOf(body);
  if (index < 0) throw new Error(`Could not find the setProp case body ${body}.`);
  const labels = setProp.slice(0, index).match(/(?:case "[^"]+": )+$/);
  if (!labels) throw new Error(`No case labels before ${body}.`);
  return [...labels[0].matchAll(/case "([^"]+)"/g)].map((m) => m[1]);
}

const aliases = [...match(/aliases = new Map\(\[(.*?)\]\)/, 'the attribute aliases')[1].matchAll(/\["([^"]+)", "([^"]+)"\]/g)].map((m) => [m[1], m[2]]);
for (const m of setProp.matchAll(/case "(\w+)": setValueForKnownAttribute\(domElement, "([^"]+)", value\)/g)) aliases.push([m[1], m[2]]);
for (const m of setProp.matchAll(/case "(\w+)": setValueForNamespacedAttribute\( domElement, \w+, "([^"]+)", value \)/g)) aliases.push([m[1], m[2]]);
for (const m of setProp.matchAll(/case "(\w+)": if \([^)]*\) \{ domElement\.removeAttribute\("([^"]+)"\)/g)) aliases.push([m[1], m[2]]);

const unitless = match(/unitlessNumbers = new Set\( "([^"]+)"\.split/, 'the unitless style names')[1].split(' ');
const booleans = casesBefore('value && "function" !== typeof value && "symbol" !== typeof value ? domElement.setAttribute(key, "")');
const booleanish = casesBefore('null != value && "function" !== typeof value && "symbol" !== typeof value ? (checkAttributeStringCoercion(value, key), domElement.setAttribute(key, "" + value))');
const ignored = [...setProp.matchAll(/((?:case "[^"]+": )+)break;/g)].flatMap((m) => [...m[1].matchAll(/case "([^"]+)"/g)].map((c) => c[1]));
const events = [...text.matchAll(/registerSimpleEvent\("(\w+)", "(on\w+)"\)/g)]
  .map((m) => [m[2], m[1]])
  .filter(([reactName, domName]) => reactName.slice(2).toLowerCase() !== domName);

const list = (values) => values.map((v) => `  ${JSON.stringify(v)},`).join('\n');
const pairs = (values) => values.map(([k, v]) => `  [${JSON.stringify(k)}, ${JSON.stringify(v)}],`).join('\n');
const output = `// Generated by scripts/react-dom-tables.mjs from react-dom ${version}. Do not edit.

/** JSX prop names that react-dom writes under a different attribute name. */
export const ATTRIBUTE_ALIASES: ReadonlyMap<string, string> = new Map([
${pairs(aliases)}
]);

/** Style names whose numeric values react-dom writes without a px unit. */
export const UNITLESS_STYLES: ReadonlySet<string> = new Set([
${list(unitless)}
]);

/** Props that react-dom renders as an empty attribute when truthy and omits otherwise. */
export const BOOLEAN_ATTRIBUTES: ReadonlySet<string> = new Set([
${list(booleans)}
]);

/** Props that react-dom renders as "true" or "false" when given a boolean. */
export const BOOLEANISH_ATTRIBUTES: ReadonlySet<string> = new Set([
${list(booleanish)}
]);

/** Props that react-dom never writes to the DOM element. */
export const IGNORED_PROPS: ReadonlySet<string> = new Set([
${list(['children', ...ignored])}
]);

/** React event props whose DOM event name is not the lowercased prop name without "on". */
export const EVENT_ALIASES: ReadonlyMap<string, string> = new Map([
${pairs(events)}
]);
`;

if (flag === '--check') {
  if (readFileSync(target, 'utf8') !== output) {
    console.error(`${target} differs from a fresh run against react-dom ${version}.`);
    process.exit(1);
  }
  console.log(`src/util/reactDomTables.ts matches react-dom ${version}.`);
} else {
  writeFileSync(target, output);
}

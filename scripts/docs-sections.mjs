#!/usr/bin/env node
// Lists, for every component page in apps/docs, the H2 and H3 sections that shadcn/ui's Base UI page lacks and the ones it has that ours lacks,
// and the pages whose installation steps differ from upstream's.
// Usage: node scripts/docs-sections.mjs <path to a shadcn/ui checkout at d2fba50> > scripts/docs-sections-audit.md
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { BASE_UI_PAGES } from '../apps/docs/registry/links.ts';

const upstreamRoot = process.argv[2];
if (!upstreamRoot) {
  console.error('usage: node scripts/docs-sections.mjs <shadcn/ui checkout>');
  process.exit(1);
}
const upstreamDir = join(upstreamRoot, 'apps/v4/content/docs/components/base');
const oursDir = new URL('../apps/docs/content/docs/components/', import.meta.url).pathname;

const rtlGuide = 'To enable RTL support in Sveltery UI, see the [RTL configuration guide](/docs/rtl).';

// Upstream writes the installation steps as <Step> tags and ours as ### headings inside <Steps>, so installSteps compares them apart.
function headings(file) {
  const found = [];
  const paragraphs = new Map();
  let fence = null;
  let steps = 0;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const marker = /^\s*(`{3,}|~{3,})/u.exec(line)?.[1];
    if (marker && (!fence || marker.startsWith(fence))) {
      fence = fence ? null : marker;
      continue;
    }
    if (fence) continue;
    if (/^\s*<Steps[\s>]/u.test(line)) steps++;
    if (/^\s*<\/Steps>/u.test(line)) steps--;
    const heading = /^(#{2,3})\s+(.+?)\s*$/u.exec(line);
    if (heading && steps === 0) found.push({ level: heading[1].length, text: heading[2] });
    else if (line.trim() && found.length && !paragraphs.has(found.at(-1))) paragraphs.set(found.at(-1), line.trim());
  }
  return Object.assign(found, { firstLine: (text) => paragraphs.get(found.find((heading) => key(heading.text) === text)) });
}

const key = (text) => text.replace(/\[([^\]]*)\]\([^)]*\)/gu, '$1').replace(/[`*_]/gu, '').trim().toLowerCase();
const levelKey = (heading) => `${heading.level} ${key(heading.text)}`;
const show = ({ level, text }) => `${'#'.repeat(level)} ${text}`;

// Each tab's steps under the Installation heading. A tab without steps has the command alone, which reads as one "run" step.
function installSteps(file, tab, step) {
  const found = { cli: [], manual: [] };
  let section = false;
  let current = null;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (/^## /u.test(line)) section = line === '## Installation';
    if (!section) continue;
    current = tab.exec(line)?.[1] ?? current;
    const text = step.exec(line)?.[1];
    if (current && text) found[current].push(stepKey(text));
  }
  if (found.cli[0] !== 'run') found.cli.unshift('run');
  return found;
}

// Upstream and ours word the steps every page shares differently, so those compare by what they do.
const stepKey = (text) => {
  const step = key(text).replace(/[.:]$/u, '');
  if (/^install the required .* dependencies$/u.test(step)) return 'add components';
  if (/^install the (following )?dependenc/u.test(step)) return 'install';
  if (/^copy/u.test(step)) return 'copy';
  if (/^update the import paths/u.test(step)) return 'imports';
  if (/^run the following command/u.test(step)) return 'run';
  return step;
};

const lines = [
  '# Docs sections audit',
  '',
  `Generated by \`node scripts/docs-sections.mjs <shadcn/ui checkout>\` against \`apps/v4/content/docs/components/base\`. Headings inside fenced code and installation steps are not compared as sections. A heading counts as the same when its level and text match, ignoring case, code marks and links.`,
  '',
];
const pages = readdirSync(oursDir).filter((file) => file.endsWith('.md') && file !== 'index.md').map((file) => file.slice(0, -3)).sort();
const ownPages = [];
const noRtlGuide = [];
const stepDiffs = [];
for (const page of pages) {
  const upstreamFile = join(upstreamDir, `${page}.mdx`);
  if (!existsSync(upstreamFile)) {
    ownPages.push(page);
    continue;
  }
  const ours = headings(join(oursDir, `${page}.md`));
  const theirs = headings(upstreamFile);
  // An item in BASE_UI_PAGES has an `api` link, and links.test.ts checks that its page links the same Base UI page.
  if (page in BASE_UI_PAGES && !theirs.some((heading) => key(heading.text) === 'api reference')) theirs.push({ level: 2, text: 'API Reference' });
  const theirKeys = new Set(theirs.map(levelKey));
  const ourKeys = new Set(ours.map(levelKey));
  const extra = ours.filter((heading) => !theirKeys.has(levelKey(heading)));
  const missing = theirs.filter((heading) => !ourKeys.has(levelKey(heading)));
  const ourSteps = installSteps(join(oursDir, `${page}.md`), /<InstallTab value="(cli|manual)">/u, /^###\s+(.+?)\s*$/u);
  const theirSteps = installSteps(upstreamFile, /<TabsContent value="(cli|manual)">/u, /<Step>(.+?)<\/Step>/u);
  for (const tab of ['cli', 'manual']) {
    if (ourSteps[tab].join() !== theirSteps[tab].join()) stepDiffs.push(`- \`${page}\` ${tab}: ${ourSteps[tab].join(', ') || 'none'} here, ${theirSteps[tab].join(', ') || 'none'} upstream`);
  }
  if (ours.some((heading) => key(heading.text) === 'rtl') && ours.firstLine('rtl') !== rtlGuide) noRtlGuide.push(page);
  if (!extra.length && !missing.length) continue;
  lines.push(`## ${page}`, '');
  if (extra.length) lines.push('Upstream lacks:', '', ...extra.map((heading) => `- \`${show(heading)}\``), '');
  if (missing.length) lines.push('Missing here:', '', ...missing.map((heading) => `- \`${show(heading)}\``), '');
}
const upstreamOnly = readdirSync(upstreamDir).filter((file) => file.endsWith('.mdx')).map((file) => file.slice(0, -4)).filter((page) => !pages.includes(page)).sort();
lines.push('## Installation steps', '', 'Steps compare by what they do: `run` the CLI command, `install` packages, `add components` the item needs, `copy` the source, update the `imports`. Other steps compare by their text.', '', ...(stepDiffs.length ? stepDiffs : ['No page differs.']), '');
lines.push('## RTL guide line', '', `Every upstream RTL section opens with the RTL guide line (\`${rtlGuide}\`). RTL sections here without it: ${noRtlGuide.map((page) => `\`${page}\``).join(', ') || 'none'}.`, '');
lines.push('## Pages', '', `Upstream has no page for: ${ownPages.map((page) => `\`${page}\``).join(', ') || 'none'}.`, '', `No page here for upstream's: ${upstreamOnly.map((page) => `\`${page}\``).join(', ') || 'none'}.`);
console.log(lines.join('\n'));
